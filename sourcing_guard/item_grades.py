def has_plastic_marker(product_name: str | None) -> bool:
    """상품명에 합성수지 재질 표지어가 있는가. ALIASES_IF_PLASTIC 의 조건이다."""
    return any(m in (product_name or "") for m in _PLASTIC_MARKERS)


def has_child_marker(product_name: str | None) -> bool:
    """상품명에 어린이 표지어가 있는가. ALIASES_IF_CHILD_MARKED 의 조건이다."""
    return any(m in (product_name or "") for m in _CHILD_MARKERS)


